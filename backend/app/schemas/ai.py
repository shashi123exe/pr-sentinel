"""Pydantic schemas for AI review output and structured Gemini responses."""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from app.db.models import Category, Severity


class AIFinding(BaseModel):
    """An issue identified by Gemini AI review on a pull request diff."""

    model_config = ConfigDict(from_attributes=True)

    title: str = Field(
        ...,
        min_length=1,
        max_length=200,
        description="Concise, actionable headline describing the issue (max 200 chars)",
    )
    severity: Severity = Field(
        ...,
        description="Severity assessment: critical, high, medium, low",
    )
    category: Category = Field(
        ...,
        description=(
            "Taxonomy category: logic_bug, security, performance, error_handling, "
            "edge_case, code_quality, testing"
        ),
    )
    file_path: str = Field(
        ...,
        min_length=1,
        max_length=500,
        description="Relative repository path of the affected file",
    )
    line_start: int | None = Field(
        default=None,
        ge=1,
        description="1-based starting line number in the HEAD file",
    )
    line_end: int | None = Field(
        default=None,
        ge=1,
        description="1-based ending line number in the HEAD file",
    )
    evidence: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description=(
            "Exact verbatim line or code span quoted from provided diff/context "
            "(max 2000 chars)"
        ),
    )
    explanation: str = Field(
        ...,
        min_length=1,
        max_length=4000,
        description=(
            "Clear technical explanation of why this is a defect or risk "
            "(max 4000 chars)"
        ),
    )
    suggested_fix: str | None = Field(
        default=None,
        max_length=4000,
        description="Optional concrete replacement code or fix advice (max 4000 chars)",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Calibrated confidence score between 0.0 and 1.0",
    )


class AIReviewResponse(BaseModel):
    """Structured response schema returned by Gemini AI review."""

    model_config = ConfigDict(from_attributes=True)

    findings: list[AIFinding] = Field(
        default_factory=list,
        description="List of demonstrable issues identified in the code",
    )


class AIReviewResult(BaseModel):
    """Overall outcome of the AI review process across all processed batches."""

    model_config = ConfigDict(from_attributes=True)

    findings: list[AIFinding] = Field(
        default_factory=list,
        description="Aggregated list of valid AI findings across all batches",
    )
    tokens_in: int = Field(
        default=0,
        ge=0,
        description="Total prompt tokens consumed across all Gemini calls",
    )
    tokens_out: int = Field(
        default=0,
        ge=0,
        description="Total candidate/completion tokens generated by Gemini",
    )
    model: str = Field(
        ...,
        description="Gemini model identifier used for analysis",
    )
    truncated: bool = Field(
        default=False,
        description=(
            "True if any file, hunk, or context was dropped due to token budget caps"
        ),
    )
    batches: int = Field(
        default=0,
        ge=0,
        description="Number of batches dispatched to the model",
    )
    errors: list[str] = Field(
        default_factory=list,
        description="Non-fatal errors or repair failure notes recorded during batch",
    )
    dropped_content: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Audit log of items dropped due to budget limits",
    )
